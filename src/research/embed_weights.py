"""Embed a velocity-ensemble weight file (flat float32, members back to back) into src/main.py.

  python src/research/embed_weights.py src/weights/vel.bin [--main src/main.py]
  python src/research/embed_weights.py src/weights/vel_la.bin --lookahead 120     # look-ahead ensemble (D-054)

Weights are quantised to int8 with one float32 scale per output row (main.VelNet.quantise); biases stay
float32. The blob is base64 (decoded in C by binascii, so loading costs no extra Python objects) and replaces the block between
the EMBEDDED-WEIGHTS markers in main.py. main.py then needs no external file.
"""
from __future__ import annotations

import argparse
import base64
import os
import sys


sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import main as pf  # noqa: E402

BEGIN = "# ---- EMBEDDED-WEIGHTS-BEGIN (generated by research/embed_weights.py; do not edit) ----"
END = "# ---- EMBEDDED-WEIGHTS-END ----"
LA_BEGIN = "# ---- LA-WEIGHTS-BEGIN (generated by research/embed_weights.py --lookahead; do not edit) ----"
LA_END = "# ---- LA-WEIGHTS-END ----"


def pack(path):
    """Quantise with main.VelNet (int8 + per-row scale) and serialise: scale, q, bias per layer."""
    net = pf.VelNet(path)
    parts = []
    for mem in net.layers:
        for sc, q, b in mem:
            parts += [sc.astype("<f4").tobytes(), q.tobytes(), b.astype("<f4").tobytes()]
    return net.k, b"".join(parts)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("weights")
    ap.add_argument("--lookahead", type=int, default=0, help="embed as the look-ahead ensemble with this lag (samples)")
    ap.add_argument("--main", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "main.py"))
    a = ap.parse_args()
    k, blob = pack(a.weights)
    b64 = base64.b64encode(blob).decode("ascii")
    lines = [b64[i:i + 100] for i in range(0, len(b64), 100)]
    if a.lookahead:
        b0, b1 = LA_BEGIN, LA_END
        block = [b0, f"_LA_MEMBERS = {k}", f"_LA_LAG = {a.lookahead}", "_LA_B64 = ("]
    else:
        b0, b1 = BEGIN, END
        block = [b0, f"_EMB_MEMBERS = {k}", "_EMB_B64 = ("]
    block += [f"    b\"{ln}\"" for ln in lines]
    block += [")", b1]
    src = open(a.main, encoding="utf-8").read()
    i, j = src.index(b0), src.index(b1) + len(b1)
    src = src[:i] + "\n".join(block) + src[j:]
    with open(a.main, "w", encoding="utf-8", newline="\n") as f:
        f.write(src)
    print(f"embedded {k} members, {len(blob)} bytes ({len(b64)} base64 chars) from {a.weights} into {a.main}")


if __name__ == "__main__":
    main()
