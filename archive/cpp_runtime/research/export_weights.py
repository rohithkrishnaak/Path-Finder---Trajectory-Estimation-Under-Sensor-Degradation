"""Export trained velocity-net weights (npz) to the flat float32 file read by the C++ runtime and to src/core/weights.hpp.

  python export_weights.py weights/vel.npz --bin weights/vel.bin [--header src/core/weights.hpp]
"""
import argparse

import numpy as np

ORDER = ("l1.weight", "l1.bias", "l2.weight", "l2.bias", "l3.weight", "l3.bias")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("npz")
    ap.add_argument("--bin")
    ap.add_argument("--header")
    a = ap.parse_args()
    d = np.load(a.npz)
    flat = np.concatenate([d[k].astype("<f4").ravel() for k in ORDER])
    print("floats:", flat.size, "bytes:", flat.nbytes)
    if a.bin:
        flat.tofile(a.bin)
    if a.header:
        with open(a.header, "w", newline="\n") as f:
            f.write("// Generated by research/export_weights.py. Do not edit.\n#pragma once\nnamespace pf {\n")
            f.write(f"constexpr int WEIGHTS_N = {flat.size};\n")
            f.write("static const float WEIGHTS[WEIGHTS_N] = {\n")
            for i in range(0, flat.size, 8):
                f.write(", ".join(f"{x:.8e}f" for x in flat[i:i + 8]) + ",\n")
            f.write("};\n}  // namespace pf\n")


if __name__ == "__main__":
    main()
